import type { MagicArtwork, MagicArtworkCatalog } from "./types";

function icon(width: number, height: number, ...strokes: string[]): MagicArtwork {
  return {
    paths: strokes.map(stroke => ({
      d: stroke.split(" ").map((point, i) => {
        const [x, y] = point.split(",").map(Number);
        return `${i ? "L" : "M"}${x * width / 24} ${y * height / 24}`;
      }).join(""),
      mode: "stroke",
    })),
    filledPaths: [],
  };
}

