"""Audit the actual font cmaps and optionally regenerate the inline symbol face.

Tooling only (no project dependency):
  python3 -m venv .venv-font-tools
  .venv-font-tools/bin/pip install fonttools brotli
  .venv-font-tools/bin/python scripts/measure-font-coverage.py [--write-css]
The regular faces remain unmodified and provide complete fallback coverage.
"""
import argparse
import base64
import io
import json
import re
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'node_modules/@inkra/react/dist/assets'
FONT_FAMILY = 'Wand Defense Symbols'
parser = argparse.ArgumentParser()
parser.add_argument('--write-css', action='store_true')
args = parser.parse_args()
common = TTFont(ASSETS / 'ui-hand-xiaolai.woff2')
extended = TTFont(ASSETS / 'ui-hand-xiaolai-extended.woff2')
common_map, extended_map = common.getBestCmap(), extended.getBestCmap()
source_files = sorted(p for p in (ROOT / 'src').rglob('*') if p.suffix in ('.ts', '.tsx') and '.test.' not in p.name)
corpus = set(''.join(p.read_text() for p in source_files))
needed = sorted(ord(char) for char in corpus if ord(char) not in common_map and ord(char) in extended_map)
chinese = sorted(ord(char) for char in corpus if 0x3400 <= ord(char) <= 0x9FFF)
if not needed:
    raise RuntimeError('No extended glyphs found; check the source font installation')
if not args.write_css:
    css = (ROOT / 'src/ui/fonts.css').read_text()
    embedded = base64.b64decode(re.search(r'data:font/woff2;base64,([^"\)]+)', css).group(1))
    embedded_map = TTFont(io.BytesIO(embedded)).getBestCmap()
    missing = sorted(set(needed) - set(embedded_map))
    if missing:
        raise RuntimeError(f'Regenerate symbols: missing {missing}')
    print(json.dumps({'chineseCharacters': len(chinese), 'chineseInCommonFont': sum(code in common_map for code in chinese), 'extendedSymbols': len(needed), 'subsetBytes': len(embedded), 'allExtendedSymbolsCovered': True, 'outsideInkraFonts': ''.join(sorted(char for char in corpus if ord(char) > 127 and ord(char) not in common_map and ord(char) not in extended_map))}, ensure_ascii=False, indent=2))
    raise SystemExit(0)
original_glyphs = extended.getGlyphSet()
original_outlines = {}
for code in needed:
    pen = DecomposingRecordingPen(original_glyphs)
    original_glyphs[extended_map[code]].draw(pen)
    original_outlines[code] = pen.value
options = subset.Options()
options.name_IDs = ['*']
options.name_legacy = True
options.name_languages = ['*']
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=needed)
subsetter.subset(extended)
license_text = (ROOT / 'node_modules/@inkra/react/Xiaolai-OFL.txt').read_text()
# A modified subset has a distinct family/PostScript name; retain the OFL notice.
renames = {1: FONT_FAMILY, 2: 'Regular', 3: 'WandDefenseSymbols-Regular', 4: FONT_FAMILY, 6: 'WandDefenseSymbols-Regular', 16: FONT_FAMILY, 17: 'Regular'}
for record in extended['name'].names:
    if record.nameID in renames:
        record.string = renames[record.nameID].encode(record.getEncoding())
extended['name'].setName(license_text, 13, 3, 1, 0x409)
extended.flavor = 'woff2'
extended.recalcTimestamp = False
output = io.BytesIO()
extended.save(output)
data = output.getvalue()
result_font = TTFont(io.BytesIO(data))
result_map = result_font.getBestCmap()
result_glyphs = result_font.getGlyphSet()
for code in needed:
    after = DecomposingRecordingPen(result_glyphs)
    result_glyphs[result_map[code]].draw(after)
    if original_outlines[code] != after.value:
        raise RuntimeError(f'Glyph outline changed for U+{code:04X}')
unicode_range = ','.join(f'U+{code:04X}' for code in needed)
css = f'''/* Generated by scripts/measure-font-coverage.py --write-css.
 * Original Xiaolai SC symbol outlines; Chinese and rare-character fallbacks stay
 * in the unchanged Inkra font stack. Do not replace the full fallback fonts.
 * Source: https://github.com/lxgw/kose-font/releases/tag/v3.120
 * This embedded font is licensed separately from the game and Inkra software.
 *
{license_text}
 */
@font-face {{
  font-family: "{FONT_FAMILY}";
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url("data:font/woff2;base64,{base64.b64encode(data).decode()}") format("woff2");
  unicode-range: {unicode_range};
}}
:root {{
  --inkra-font-hand: "{FONT_FAMILY}", "Inkra Xiaolai", "Trip Map Hand", "Kaiti SC", "STKaiti", cursive;
}}
'''
if len(data) > 8192:
    raise RuntimeError(f'Symbol subset too large for inline CSS: {len(data)} bytes')
if args.write_css:
    (ROOT / 'src/ui/fonts.css').write_text(css)
print(json.dumps({'chineseCharacters': len(chinese), 'chineseInCommonFont': sum(code in common_map for code in chinese), 'symbolCharacters': ''.join(chr(code) for code in needed), 'symbolCodepoints': unicode_range, 'subsetBytes': len(data), 'extendedBytes': (ASSETS / 'ui-hand-xiaolai-extended.woff2').stat().st_size, 'outlinesUnchanged': True, 'cssWritten': args.write_css}, ensure_ascii=False, indent=2))
